#!/usr/bin/env bash
# Build and audit the tracked native project without signing or installing.
# Device and simulator configurations share one retained DerivedData directory.
# Usage: scripts/build.sh [all|debug|release|simulator]
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT" || exit 1
PROJECT="TruongScaler.xcodeproj"
SCHEME="TruongScalerApp"
APP_NAME="TruongScalerApp"
LOG_DIR="$ROOT/build/logs"
mkdir -p "$LOG_DIR"

mode="${1:-all}"
BUILD_JOBS="${TRUONGSCALER_BUILD_JOBS:-2}"
DERIVED="${TRUONGSCALER_DERIVED_DATA:-$ROOT/build/DerivedData}"
if ! [[ "$BUILD_JOBS" =~ ^[1-9][0-9]*$ ]]; then
  echo "TRUONGSCALER_BUILD_JOBS must be a positive integer" >&2
  exit 2
fi
if [ ! -d "$PROJECT" ]; then
  echo "ERROR: tracked $PROJECT is missing; restore the complete checkout." >&2
  exit 1
fi
COMMON_SETTINGS=(
  CODE_SIGNING_ALLOWED=NO
  SWIFT_STRICT_CONCURRENCY=complete
  SWIFT_TREAT_WARNINGS_AS_ERRORS=YES
  GCC_TREAT_WARNINGS_AS_ERRORS=YES
)
if [ -n "${TRUONGSCALER_BUILD_NUMBER:-}" ]; then
  case "$TRUONGSCALER_BUILD_NUMBER" in
    *[!0-9]*) echo "TRUONGSCALER_BUILD_NUMBER must contain only digits" >&2; exit 2 ;;
  esac
  COMMON_SETTINGS+=("CURRENT_PROJECT_VERSION=$TRUONGSCALER_BUILD_NUMBER")
fi

print_toolchain() {
  echo "== toolchain =="
  xcodebuild -version
  echo "xcode-select: $(xcode-select -p)"
  echo "iphoneos SDK: $(xcrun --sdk iphoneos --show-sdk-path)"
  echo "iphoneos SDK version: $(xcrun --sdk iphoneos --show-sdk-version)"
  swift --version 2>&1 | head -2
  echo
}

audit_product() {
  local app="$1" config="$2"
  python3 scripts/validate_built_metadata.py --app "$app" --expect-config "$config" || return 1
  python3 ModelConversionTools/verify_production_assets.py --built-app "$app" || return 1
}

build_product() {
  local config="$1" sdk="$2" destination="$3" label="$4"
  local log="$LOG_DIR/build-${label}-${config}.log"
  local config_settings=(COPY_PHASE_STRIP=NO)
  if [ "$config" = Release ]; then
    config_settings+=(
      SWIFT_OPTIMIZATION_LEVEL=-O
      GCC_OPTIMIZATION_LEVEL=s
      DEBUG_INFORMATION_FORMAT=dwarf-with-dsym
      GCC_GENERATE_DEBUGGING_SYMBOLS=YES
      DEAD_CODE_STRIPPING=YES
      DEPLOYMENT_POSTPROCESSING=NO
      STRIP_INSTALLED_PRODUCT=NO
    )
  else
    config_settings+=(DEPLOYMENT_POSTPROCESSING=NO STRIP_INSTALLED_PRODUCT=NO)
  fi
  echo "== $label build ($config) =="
  echo "log: $log"
  xcodebuild \
    -jobs "$BUILD_JOBS" \
    -project "$PROJECT" \
    -scheme "$SCHEME" \
    -configuration "$config" \
    -sdk "$sdk" \
    -destination "$destination" \
    -derivedDataPath "$DERIVED" \
    "${COMMON_SETTINGS[@]}" "${config_settings[@]}" \
    build >"$log" 2>&1
  local status=$?
  if [ "$status" -eq 0 ]; then
    local app="$DERIVED/Build/Products/${config}-${sdk}/${APP_NAME}.app"
    if [ "$config" = Release ]; then
      # A command-line STRIP_STYLE=all also strips Swift package relocatable .o files,
      # which destroys symbols still needed by the linker. Strip only linked products;
      # their matching external dSYMs were generated by Xcode before this operation.
      xcrun strip -S -x "$app/$APP_NAME" || return 1
      xcrun strip -S -x "$app/PlugIns/TruongScalerLiveActivityExtension.appex/TruongScalerLiveActivityExtension" || return 1
    fi
    audit_product "$app" "$config" || return 1
    echo "PASS: $config $label unsigned app/widget build and resource audit"
    echo "artifact: $app"
    /usr/bin/du -sh "$app" | sed 's/^/size: /'
  else
    echo "FAIL: $config $label build (exit $status)"
    grep -E "error:" "$log" | sort -u | head -40
  fi
  return "$status"
}

build_device() {
  build_product "$1" iphoneos 'generic/platform=iOS' device
}

print_toolchain
overall=0
case "$mode" in
  debug) build_device Debug || overall=1 ;;
  release) build_device Release || overall=1 ;;
  simulator) build_product Debug iphonesimulator 'generic/platform=iOS Simulator' simulator || overall=1 ;;
  all)
    build_device Debug || overall=1
    build_device Release || overall=1
    ;;
  *) echo "unknown mode: $mode" >&2; exit 2 ;;
esac
if [ "$overall" -eq 0 ]; then
  echo "RESULT: PASS"
else
  echo "RESULT: FAIL"
fi
exit "$overall"
